#!/bin/bash

# =============================================================================
# VPN Server Setup Script (OpenVPN & WireGuard)
# Compatible with Ubuntu 22.04 LTS
# =============================================================================

set -euo pipefail

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Configuration variables
VPN_TYPE=""
SERVER_IP=""
VPN_PORT=""
CLIENT_NAME="client1"
OPENVPN_DIR="/etc/openvpn"
WIREGUARD_DIR="/etc/wireguard"

# =============================================================================
# Utility Functions
# =============================================================================

log() {
    echo -e "${GREEN}[$(date +'%Y-%m-%d %H:%M:%S')] $1${NC}"
}

warn() {
    echo -e "${YELLOW}[WARNING] $1${NC}"
}

error() {
    echo -e "${RED}[ERROR] $1${NC}"
    exit 1
}

check_root() {
    if [[ $EUID -ne 0 ]]; then
        error "This script must be run as root. Use: sudo $0"
    fi
}

get_server_ip() {
    # Try to get public IP, fallback to local IP
    SERVER_IP=$(curl -s ifconfig.me 2>/dev/null || curl -s ipinfo.io/ip 2>/dev/null || ip route get 1.1.1.1 | awk '{print $7; exit}')
    if [[ -z "$SERVER_IP" ]]; then
        error "Could not determine server IP address"
    fi
    log "Detected server IP: $SERVER_IP"
}

update_system() {
    log "Updating system packages..."
    apt update && apt upgrade -y
    apt install -y curl wget ufw iptables-persistent
}

enable_ip_forwarding() {
    log "Enabling IP forwarding..."
    
    # Enable IP forwarding permanently
    echo 'net.ipv4.ip_forward=1' >> /etc/sysctl.conf
    echo 'net.ipv6.conf.all.forwarding=1' >> /etc/sysctl.conf
    
    # Apply immediately
    sysctl -p
    
    log "IP forwarding enabled"
}

# =============================================================================
# OpenVPN Setup Functions
# =============================================================================

install_openvpn() {
    log "Installing OpenVPN..."
    
    apt install -y openvpn easy-rsa
    
    # Setup PKI directory
    make-cadir $OPENVPN_DIR/easy-rsa
    cd $OPENVPN_DIR/easy-rsa
    
    log "OpenVPN installed successfully"
}

configure_openvpn_pki() {
    log "Configuring OpenVPN PKI (Public Key Infrastructure)..."
    
    cd $OPENVPN_DIR/easy-rsa
    
    # Initialize PKI
    ./easyrsa init-pki
    
    # Build CA (Certificate Authority) - non-interactive
    echo -e "\n\n\n\n\n\n\n" | ./easyrsa build-ca nopass
    
    # Generate server certificate and key
    echo -e "\n" | ./easyrsa build-server-full server nopass
    
    # Generate client certificate and key
    echo -e "\n" | ./easyrsa build-client-full $CLIENT_NAME nopass
    
    # Generate Diffie-Hellman parameters
    ./easyrsa gen-dh
    
    # Generate TLS-auth key
    openvpn --genkey secret pki/ta.key
    
    # Copy certificates to OpenVPN directory
    cp pki/ca.crt $OPENVPN_DIR/
    cp pki/issued/server.crt $OPENVPN_DIR/
    cp pki/private/server.key $OPENVPN_DIR/
    cp pki/dh.pem $OPENVPN_DIR/
    cp pki/ta.key $OPENVPN_DIR/
    
    log "PKI configuration completed"
}

create_openvpn_server_config() {
    log "Creating OpenVPN server configuration..."
    
    cat > $OPENVPN_DIR/server.conf << EOF
# OpenVPN Server Configuration
# Generated by VPN Setup Script

port $VPN_PORT
proto udp
dev tun

# SSL/TLS root certificate (ca), certificate (cert), and private key (key)
ca ca.crt
cert server.crt
key server.key
dh dh.pem

# Network topology
topology subnet

# Configure server mode and supply a VPN subnet
server 10.8.0.0 255.255.255.0

# Maintain a record of client <-> virtual IP address associations
ifconfig-pool-persist /var/log/openvpn/ipp.txt

# Push routes to the client to allow it to reach other private subnets
push "redirect-gateway def1 bypass-dhcp"
push "dhcp-option DNS 8.8.8.8"
push "dhcp-option DNS 8.8.4.4"

# Client-to-client communication
client-to-client

# Keep alive
keepalive 10 120

# TLS security
tls-auth ta.key 0
cipher AES-256-GCM
auth SHA256

# Compression
compress lz4-v2
push "compress lz4-v2"

# Maximum number of concurrently connected clients
max-clients 10

# Run with reduced privileges
user nobody
group nogroup

# Persist keys and tunnel
persist-key
persist-tun

# Output a short status file
status /var/log/openvpn/openvpn-status.log

# Log verbosity
verb 3
explicit-exit-notify 1
EOF

    # Create log directory
    mkdir -p /var/log/openvpn
    
    log "OpenVPN server configuration created"
}

create_openvpn_client_config() {
    log "Creating OpenVPN client configuration..."
    
    mkdir -p /root/vpn-clients
    
    cat > /root/vpn-clients/$CLIENT_NAME.ovpn << EOF
client
dev tun
proto udp
remote $SERVER_IP $VPN_PORT
resolv-retry infinite
nobind
persist-key
persist-tun
cipher AES-256-GCM
auth SHA256
compress lz4-v2
verb 3

<ca>
$(cat $OPENVPN_DIR/easy-rsa/pki/ca.crt)
</ca>

<cert>
$(cat $OPENVPN_DIR/easy-rsa/pki/issued/$CLIENT_NAME.crt)
</cert>

<key>
$(cat $OPENVPN_DIR/easy-rsa/pki/private/$CLIENT_NAME.key)
</key>

<tls-auth>
$(cat $OPENVPN_DIR/ta.key)
</tls-auth>
key-direction 1
EOF

    log "Client configuration created: /root/vpn-clients/$CLIENT_NAME.ovpn"
}

# =============================================================================
# WireGuard Setup Functions
# =============================================================================

install_wireguard() {
    log "Installing WireGuard..."
    
    apt install -y wireguard qrencode
    
    log "WireGuard installed successfully"
}

configure_wireguard() {
    log "Configuring WireGuard..."
    
    # Generate server keys
    wg genkey | tee $WIREGUARD_DIR/private.key | wg pubkey > $WIREGUARD_DIR/public.key
    
    # Generate client keys
    wg genkey | tee $WIREGUARD_DIR/client_private.key | wg pubkey > $WIREGUARD_DIR/client_public.key
    
    # Set permissions
    chmod 600 $WIREGUARD_DIR/private.key $WIREGUARD_DIR/client_private.key
    
    # Read keys
    SERVER_PRIVATE_KEY=$(cat $WIREGUARD_DIR/private.key)
    SERVER_PUBLIC_KEY=$(cat $WIREGUARD_DIR/public.key)
    CLIENT_PRIVATE_KEY=$(cat $WIREGUARD_DIR/client_private.key)
    CLIENT_PUBLIC_KEY=$(cat $WIREGUARD_DIR/client_public.key)
    
    # Create server configuration
    cat > $WIREGUARD_DIR/wg0.conf << EOF
[Interface]
# Server configuration
PrivateKey = $SERVER_PRIVATE_KEY
Address = 10.0.0.1/24
ListenPort = $VPN_PORT
SaveConfig = true

# Enable IP forwarding and NAT
PostUp = iptables -A FORWARD -i wg0 -j ACCEPT; iptables -t nat -A POSTROUTING -o eth0 -j MASQUERADE
PostDown = iptables -D FORWARD -i wg0 -j ACCEPT; iptables -t nat -D POSTROUTING -o eth0 -j MASQUERADE

[Peer]
# Client configuration
PublicKey = $CLIENT_PUBLIC_KEY
AllowedIPs = 10.0.0.2/32
EOF

    log "WireGuard server configuration created"
}

create_wireguard_client_config() {
    log "Creating WireGuard client configuration..."
    
    mkdir -p /root/vpn-clients
    
    SERVER_PUBLIC_KEY=$(cat $WIREGUARD_DIR/public.key)
    CLIENT_PRIVATE_KEY=$(cat $WIREGUARD_DIR/client_private.key)
    
    cat > /root/vpn-clients/wg0-client.conf << EOF
[Interface]
PrivateKey = $CLIENT_PRIVATE_KEY
Address = 10.0.0.2/24
DNS = 8.8.8.8

[Peer]
PublicKey = $SERVER_PUBLIC_KEY
Endpoint = $SERVER_IP:$VPN_PORT
AllowedIPs = 0.0.0.0/0
PersistentKeepalive = 25
EOF

    # Generate QR code for mobile devices
    qrencode -t ansiutf8 < /root/vpn-clients/wg0-client.conf
    qrencode -o /root/vpn-clients/wg0-client-qr.png < /root/vpn-clients/wg0-client.conf
    
    log "WireGuard client configuration created: /root/vpn-clients/wg0-client.conf"
    log "QR code generated: /root/vpn-clients/wg0-client-qr.png"
}

# =============================================================================
# Firewall Configuration
# =============================================================================

configure_firewall() {
    log "Configuring firewall rules..."
    
    # Reset UFW to default
    ufw --force reset
    ufw default deny incoming
    ufw default allow outgoing
    
    # Allow SSH (important!)
    ufw allow ssh
    
    # Allow VPN port
    ufw allow $VPN_PORT/udp
    
    if [[ "$VPN_TYPE" == "openvpn" ]]; then
        # OpenVPN specific rules
        ufw allow in on tun0
        ufw allow out on tun0
        
        # NAT rules for OpenVPN
        iptables -t nat -A POSTROUTING -s 10.8.0.0/24 -o eth0 -j MASQUERADE
        iptables -A FORWARD -i tun0 -j ACCEPT
        iptables -A FORWARD -o tun0 -j ACCEPT
        
    elif [[ "$VPN_TYPE" == "wireguard" ]]; then
        # WireGuard specific rules
        ufw allow in on wg0
        ufw allow out on wg0
    fi
    
    # Enable UFW
    ufw --force enable
    
    # Save iptables rules
    iptables-save > /etc/iptables/rules.v4
    
    log "Firewall configured successfully"
}

# =============================================================================
# Service Management
# =============================================================================

enable_services() {
    log "Enabling VPN service..."
    
    if [[ "$VPN_TYPE" == "openvpn" ]]; then
        systemctl enable openvpn@server
        systemctl start openvpn@server
        systemctl status openvpn@server --no-pager
        
    elif [[ "$VPN_TYPE" == "wireguard" ]]; then
        systemctl enable wg-quick@wg0
        systemctl start wg-quick@wg0
        systemctl status wg-quick@wg0 --no-pager
    fi
    
    log "VPN service enabled and started"
}

