# =============================================================================
# Main Menu and Setup
# =============================================================================

show_menu() {
    echo
    echo "=========================================================================="
    echo -e "${GREEN}VPN Server Setup Script${NC}"
    echo "=========================================================================="
    echo
    echo "This script will set up a secure VPN server on Ubuntu 22.04"
    echo
    echo "Choose your VPN type:"
    echo "1) OpenVPN (Traditional, widely supported)"
    echo "2) WireGuard (Modern, faster, simpler)"
    echo "3) Exit"
    echo
}

get_user_input() {
    while true; do
        show_menu
        read -p "Enter your choice (1-3): " choice
        
        case $choice in
            1)
                VPN_TYPE="openvpn"
                VPN_PORT="1194"
                break
                ;;
            2)
                VPN_TYPE="wireguard"
                VPN_PORT="51820"
                break
                ;;
            3)
                echo "Exiting..."
                exit 0
                ;;
            *)
                echo "Invalid option. Please choose 1, 2, or 3."
                ;;
        esac
    done
    
    echo
    read -p "Enter VPN port (default: $VPN_PORT): " custom_port
    if [[ -n "$custom_port" ]]; then
        VPN_PORT="$custom_port"
    fi
    
    read -p "Enter client name (default: $CLIENT_NAME): " custom_client
    if [[ -n "$custom_client" ]]; then
        CLIENT_NAME="$custom_client"
    fi
}

main() {
    log "Starting VPN server setup..."
    
    check_root
    get_user_input
    get_server_ip
    update_system
    enable_ip_forwarding
    
    if [[ "$VPN_TYPE" == "openvpn" ]]; then
        install_openvpn
        configure_openvpn_pki
        create_openvpn_server_config
        create_openvpn_client_config
    elif [[ "$VPN_TYPE" == "wireguard" ]]; then
        install_wireguard
        configure_wireguard
        create_wireguard_client_config
    fi
    
    configure_firewall
    enable_services
    show_connection_instructions
    
    log "VPN setup completed successfully!"
}

# Run main function
main "$@"