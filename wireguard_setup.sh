#!/bin/bash

# =============================================================================
# WireGuard VPN Server Setup Script for Ubuntu 22.04
# =============================================================================
# This script automatically sets up a secure WireGuard VPN server with:
# - Automatic package installation
# - Random encryption keys generation
# - Client configuration generation
# - Firewall configuration (UFW)
# - Systemd service setup
# - Detailed logging and error handling
# =============================================================================

set -e  # Exit on any error

# Color codes for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Configuration variables
VPN_SERVER_IP=""
VPN_PORT="51820"
VPN_INTERFACE="wg0"
VPN_NETWORK="10.0.0.0"
VPN_SUBNET="255.255.255.0"
VPN_DNS1="8.8.8.8"
VPN_DNS2="8.8.4.4"
CLIENT_NAME="client1"
CLIENT_IP="10.0.0.2"

# Logging function
log() {
    echo -e "${GREEN}[$(date +'%Y-%m-%d %H:%M:%S')] $1${NC}"
}

warn() {
    echo -e "${YELLOW}[$(date +'%Y-%m-%d %H:%M:%S')] WARNING: $1${NC}"
}

error() {
    echo -e "${RED}[$(date +'%Y-%m-%d %H:%M:%S')] ERROR: $1${NC}"
    exit 1
}

info() {
    echo -e "${BLUE}[$(date +'%Y-%m-%d %H:%M:%S')] INFO: $1${NC}"
}

# Function to check if running as root
check_root() {
    if [[ $EUID -ne 0 ]]; then
        error "This script must be run as root (use sudo)"
    fi
}

# Function to detect server IP
detect_server_ip() {
    log "Detecting server IP address..."
    
    # Try to get the primary IP address
    if command -v ip &> /dev/null; then
        VPN_SERVER_IP=$(ip route get 8.8.8.8 | awk 'NR==1 {print $7}')
    elif command -v hostname &> /dev/null; then
        VPN_SERVER_IP=$(hostname -I | awk '{print $1}')
    else
        error "Could not detect server IP address"
    fi
    
    if [[ -z "$VPN_SERVER_IP" ]]; then
        error "Could not detect server IP address"
    fi
    
    log "Detected server IP: $VPN_SERVER_IP"
}

# Function to update system packages
update_system() {
    log "Updating system packages..."
    apt update -y || error "Failed to update package list"
    apt upgrade -y || error "Failed to upgrade packages"
    
    # Install essential packages
    log "Installing essential packages..."
    apt install -y curl wget git ufw fail2ban || error "Failed to install essential packages"
}

# Function to install WireGuard
install_wireguard() {
    log "Installing WireGuard..."
    
    # Add WireGuard repository for latest version
    log "Adding WireGuard repository..."
    apt install -y software-properties-common || error "Failed to install software-properties-common"
    add-apt-repository ppa:wireguard/wireguard -y || error "Failed to add WireGuard repository"
    apt update -y || error "Failed to update package list"
    
    # Install WireGuard
    apt install -y wireguard wireguard-tools || error "Failed to install WireGuard"
    
    # Verify installation
    if ! command -v wg &> /dev/null; then
        error "WireGuard installation failed"
    fi
    
    log "WireGuard installed successfully"
}

# Function to generate WireGuard keys
generate_keys() {
    log "Generating WireGuard keys..."
    
    # Create WireGuard directory
    mkdir -p /etc/wireguard
    cd /etc/wireguard
    
    # Generate server keys
    log "Generating server private and public keys..."
    wg genkey | tee privatekey | wg pubkey > publickey || error "Failed to generate server keys"
    
    # Generate client keys
    log "Generating client private and public keys..."
    wg genkey | tee client_privatekey | wg pubkey > client_publickey || error "Failed to generate client keys"
    
    # Set proper permissions
    chmod 600 privatekey
    chmod 600 client_privatekey
    chmod 644 publickey
    chmod 644 client_publickey
    
    # Store keys in variables
    SERVER_PRIVATE_KEY=$(cat privatekey)
    SERVER_PUBLIC_KEY=$(cat publickey)
    CLIENT_PRIVATE_KEY=$(cat client_privatekey)
    CLIENT_PUBLIC_KEY=$(cat client_publickey)
    
    log "WireGuard keys generated successfully"
}

# Function to create WireGuard server configuration
create_server_config() {
    log "Creating WireGuard server configuration..."
    
    cat > /etc/wireguard/$VPN_INTERFACE.conf << EOF
# WireGuard Server Configuration
# Generated by VPN Setup Script

[Interface]
# Server configuration
Address = $VPN_NETWORK.1/24
ListenPort = $VPN_PORT
PrivateKey = $SERVER_PRIVATE_KEY

# Enable IP forwarding
PostUp = iptables -A FORWARD -i $VPN_INTERFACE -j ACCEPT; iptables -t nat -A POSTROUTING -o eth0 -j MASQUERADE
PostDown = iptables -D FORWARD -i $VPN_INTERFACE -j ACCEPT; iptables -t nat -D POSTROUTING -o eth0 -j MASQUERADE

# DNS configuration
PostUp = iptables -A FORWARD -o $VPN_INTERFACE -j ACCEPT
PostDown = iptables -D FORWARD -o $VPN_INTERFACE -j ACCEPT

# Client configuration
[Peer]
# $CLIENT_NAME
PublicKey = $CLIENT_PUBLIC_KEY
AllowedIPs = $CLIENT_IP/32
PersistentKeepalive = 25
EOF
    
    # Set proper permissions
    chmod 600 /etc/wireguard/$VPN_INTERFACE.conf
    
    log "Server configuration created successfully"
}

# Function to create client configuration
create_client_config() {
    log "Creating client configuration file..."
    
    # Create client config directory
    mkdir -p /etc/wireguard/client-configs/
    
    cat > /etc/wireguard/client-configs/$CLIENT_NAME.conf << EOF
# WireGuard Client Configuration
# Generated by VPN Setup Script
# Client: $CLIENT_NAME

[Interface]
# Client configuration
Address = $CLIENT_IP/24
PrivateKey = $CLIENT_PRIVATE_KEY
DNS = $VPN_DNS1, $VPN_DNS2

# Prevent DNS leaks
PostUp = resolvectl dns %i $VPN_DNS1 $VPN_DNS2
PostUp = resolvectl domain %i ~.

[Peer]
# Server configuration
PublicKey = $SERVER_PUBLIC_KEY
Endpoint = $VPN_SERVER_IP:$VPN_PORT
AllowedIPs = 0.0.0.0/0, ::/0
PersistentKeepalive = 25
EOF
    
    # Set proper permissions
    chmod 644 /etc/wireguard/client-configs/$CLIENT_NAME.conf
    
    log "Client configuration created: /etc/wireguard/client-configs/$CLIENT_NAME.conf"
}

# Function to enable IP forwarding
enable_ip_forwarding() {
    log "Enabling IP forwarding..."
    
    # Enable IP forwarding
    echo 'net.ipv4.ip_forward=1' >> /etc/sysctl.conf
    echo 'net.ipv6.conf.all.forwarding=1' >> /etc/sysctl.conf
    sysctl -p || error "Failed to apply sysctl changes"
    
    log "IP forwarding enabled successfully"
}

# Function to configure firewall
configure_firewall() {
    log "Configuring firewall (UFW)..."
    
    # Reset UFW to default
    ufw --force reset || error "Failed to reset UFW"
    
    # Set default policies
    ufw default deny incoming || error "Failed to set default deny incoming"
    ufw default allow outgoing || error "Failed to set default allow outgoing"
    
    # Allow SSH (important to prevent lockout)
    ufw allow ssh || error "Failed to allow SSH"
    
    # Allow WireGuard port
    ufw allow $VPN_PORT/udp || error "Failed to allow WireGuard port"
    
    # Enable UFW
    ufw --force enable || error "Failed to enable UFW"
    
    log "Firewall configured successfully"
}

# Function to create systemd service
create_systemd_service() {
    log "Creating systemd service..."
    
    # Enable WireGuard service
    systemctl enable wg-quick@$VPN_INTERFACE || error "Failed to enable WireGuard service"
    
    log "Systemd service created and enabled"
}

# Function to start WireGuard service
start_wireguard_service() {
    log "Starting WireGuard service..."
    
    wg-quick up $VPN_INTERFACE || error "Failed to start WireGuard interface"
    
    # Check if interface is up
    if ip link show $VPN_INTERFACE &> /dev/null; then
        log "WireGuard interface started successfully"
    else
        error "WireGuard interface failed to start"
    fi
}

