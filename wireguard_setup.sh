# Function to add additional clients
add_client() {
    local new_client_name="$1"
    local new_client_ip="$2"
    
    if [[ -z "$new_client_name" ]]; then
        error "Client name is required"
    fi
    
    if [[ -z "$new_client_ip" ]]; then
        # Auto-assign IP based on existing clients
        new_client_ip=$(grep -o "10\.0\.0\.[0-9]*" /etc/wireguard/$VPN_INTERFACE.conf | sort -V | tail -1 | cut -d. -f4)
        new_client_ip=$((new_client_ip + 1))
        new_client_ip="10.0.0.$new_client_ip"
    fi
    
    log "Adding new client: $new_client_name with IP: $new_client_ip"
    
    # Generate new client keys
    cd /etc/wireguard
    wg genkey | tee ${new_client_name}_privatekey | wg pubkey > ${new_client_name}_publickey
    
    # Get the new client's public key
    NEW_CLIENT_PUBLIC_KEY=$(cat ${new_client_name}_publickey)
    
    # Add to server config
    cat >> /etc/wireguard/$VPN_INTERFACE.conf << EOF

[Peer]
# $new_client_name
PublicKey = $NEW_CLIENT_PUBLIC_KEY
AllowedIPs = $new_client_ip/32
PersistentKeepalive = 25
EOF
    
    # Create client config
    NEW_CLIENT_PRIVATE_KEY=$(cat ${new_client_name}_privatekey)
    
    cat > /etc/wireguard/client-configs/$new_client_name.conf << EOF
# WireGuard Client Configuration
# Generated by VPN Setup Script
# Client: $new_client_name

[Interface]
# Client configuration
Address = $new_client_ip/24
PrivateKey = $NEW_CLIENT_PRIVATE_KEY
DNS = $VPN_DNS1, $VPN_DNS2

# Prevent DNS leaks
PostUp = resolvectl dns %i $VPN_DNS1 $VPN_DNS2
PostUp = resolvectl domain %i ~.

[Peer]
# Server configuration
PublicKey = $SERVER_PUBLIC_KEY
Endpoint = $VPN_SERVER_IP:$VPN_PORT
AllowedIPs = 0.0.0.0/0, ::/0
PersistentKeepalive = 25
EOF
    
    # Set proper permissions
    chmod 600 ${new_client_name}_privatekey
    chmod 644 ${new_client_name}_publickey
    chmod 644 /etc/wireguard/client-configs/$new_client_name.conf
    
    # Reload WireGuard configuration
    wg syncconf $VPN_INTERFACE <(wg-quick strip $VPN_INTERFACE)
    
    log "Client $new_client_name added successfully"
    log "Client config: /etc/wireguard/client-configs/$new_client_name.conf"
}

# Function to show usage
show_usage() {
    echo "Usage: $0 [OPTIONS]"
    echo
    echo "Options:"
    echo "  --add-client NAME [IP]  Add a new client with optional IP"
    echo "  --help                  Show this help message"
    echo
    echo "Examples:"
    echo "  $0                      # Initial setup"
    echo "  $0 --add-client client2 # Add client2 with auto-assigned IP"
    echo "  $0 --add-client client3 10.0.0.5 # Add client3 with specific IP"
}

# Main execution function
main() {
    # Parse command line arguments
    while [[ $# -gt 0 ]]; do
        case $1 in
            --add-client)
                if [[ -z "$2" ]]; then
                    error "Client name is required for --add-client"
                fi
                add_client "$2" "$3"
                exit 0
                ;;
            --help)
                show_usage
                exit 0
                ;;
            *)
                error "Unknown option: $1"
                ;;
        esac
        shift
    done
    
    echo "============================================================================="
    echo "🚀 WireGuard VPN Server Setup Script for Ubuntu 22.04"
    echo "============================================================================="
    echo
    
    # Check if running as root
    check_root
    
    # Detect server IP
    detect_server_ip
    
    # Update system
    update_system
    
    # Install WireGuard
    install_wireguard
    
    # Generate keys
    generate_keys
    
    # Create server configuration
    create_server_config
    
    # Create client configuration
    create_client_config
    
    # Enable IP forwarding
    enable_ip_forwarding
    
    # Configure firewall
    configure_firewall
    
    # Create systemd service
    create_systemd_service
    
    # Start WireGuard service
    start_wireguard_service
    
    # Create connection instructions
    create_instructions
    
    # Display final information
    display_final_info
}

# Run main function
main "$@"